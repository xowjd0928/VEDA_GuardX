#pragma once

#include <QColor>
#include <QImage>

/**
 * 카메라 스냅샷에서 **구조선만** 뽑아 투명 오버레이로 만든다 (FLOOR MAP 배경).
 *
 * OpenCV 에 의존하지 않는다 — VMS PC 에 DLL 을 더 얹지 않으려는 결정이고,
 * 여기 필요한 연산은 전부 3×3 컨볼루션과 연결성분 라벨링뿐이다.
 *
 * @section why 왜 단순 Sobel 이 아닌가 (2026-08-24)
 *
 * 예전 구현은 원본에 Sobel 을 걸고 크기 임계(기본 80) 하나로 잘랐다. 현장
 * 바닥이 **광택 대리석**이라 돌 무늬와 조명 반사가 그대로 선으로 나왔다
 * (사용자 신고). 임계를 올려도 소용이 없다 — 실측해 보면 **반사가 실제
 * 구조선(바닥 타일 경계)보다 더 강하다.** 세기로는 가를 수 없는 문제다.
 *
 * 가르는 축은 세기가 아니라 **선명도**다:
 *  - 계단형 경계(타일 경계·벽 모서리·물건 윤곽)는 좁고 가파르다.
 *  - 반사·돌 무늬는 넓고 무르다(이미 흐릿한 밝기 변화).
 *
 * 그래서 **두 척도의 기울기 비**로 판정한다 — 가는 블러(σ≈0.6)의 기울기를
 * 굵은 블러(σ≈3)의 기울기로 나눈 값. 계단이면 이 비가 크고(3~6), 무른
 * 얼룩이면 1 근처다. 실측(현장 스냅샷): 반사·무늬는 사라지고 타일 사각형과
 * 몰딩은 남았다.
 *
 * 뒤이어 비최대 억제로 선을 1px 로 만들고, **짧은 성분을 버린다**(점처럼
 * 흩어진 잔여물 제거). 어안 렌즈라 직선 검출(Hough)은 쓸 수 없다 — 이
 * 카메라에서 실제 직선은 화면에서 곡선이다.
 *
 * @section tuning 조정 (QSettings("GuardX","VMS"))
 *  - `edge_sharpness` (기본 3.5) — 척도비 하한. 올리면 더 가파른 것만 남는다.
 *  - `edge_mag_min`   (기본 30)  — 기울기 하한. 아주 흐린 경계를 버린다.
 *  - `edge_min_len`   (기본 60)  — 성분 최소 픽셀 수.
 * 벽지·조명이 바뀌면 재빌드 없이 이 셋으로 맞춘다.
 */
class EdgeMapGenerator
{
public:
    /**
     * 엣지만 남긴 투명 ARGB 이미지를 만든다.
     *
     * @param source     합성한 채널 스냅샷.
     * @param threshold  기울기 하한의 기본값 (QSettings `edge_mag_min` 이
     *                   있으면 그쪽이 이긴다). 호출부 호환을 위해 남긴 인자다.
     * @param edge_color 선 색. 기본은 중립 회색 — 그 위에 그려지는 동선·박스가
     *                   전부 의미색이라 배경이 되는 이 선만 중립이어야 읽힌다.
     * @return           선만 담긴 투명 이미지 (원본과 같은 크기).
     */
    static QImage generate_edge_overlay(const QImage &source,
                                        int threshold = 30,
                                        const QColor &edge_color = QColor(0xB4, 0xB0, 0xA8, 170));
};
